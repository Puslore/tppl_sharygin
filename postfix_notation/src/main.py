# Краткое описание модуля, которое также отображается в документации Python.
"""A small, friendly postfix-notation stack machine."""

# Импортируем разбор аргументов командной строки.
import argparse
# Импортируем проверку чисел с плавающей точкой на конечность.
import math
# Импортируем стандартный поток вывода для трассировки вычислений.
import sys
# Импортируем тип текстового потока для аннотации аргумента trace.
from typing import TextIO

# Объявляем допустимые типы значений, которые может хранить стек.
Number = int | float
# Перечисляем арифметические и специальные операции стековой машины.
OPERATORS = {"+", "-", "*", "/", "~", "!"}


# Функция преобразует один текстовый токен в число и сообщает об ошибке, если преобразование невозможно.
def _parse_number(token: str) -> Number:
    # Сначала пробуем сохранить целочисленное значение без потери точности.
    try:
        # Возвращаем токен как целое число, если он записан в целочисленном формате.
        return int(token)
    # Если целочисленное преобразование не удалось, проверяем формат числа с плавающей точкой.
    except ValueError:
        # Начинаем отдельный блок обработки числа с плавающей точкой.
        try:
            # Преобразуем десятичный токен в число с плавающей точкой.
            value = float(token)
        # Если строка не является числом, создаём понятную пользователю ошибку.
        except ValueError as error:
            # Добавляем исходный токен в сообщение и сохраняем исходное исключение как причину.
            raise ValueError(f"Не удалось распознать операнд {token!r}.") from error
        # Отвергаем бесконечность и NaN, которые float может принять как специальные значения.
        if not math.isfinite(value):
            # Сообщаем, что операнд должен быть конечным числом.
            raise ValueError(f"Операнд {token!r} должен быть конечным числом.")
        # Возвращаем успешно распознанное конечное число с плавающей точкой.
        return value


# Функция вычисляет постфиксное выражение и при необходимости записывает состояние стека после каждого токена.
def evaluate(expression: str, *, trace: TextIO | None = None) -> Number:
    # Разбиваем выражение на токены по любому количеству пробельных символов.
    tokens = expression.split()
    # Проверяем, что после разбиения осталось хотя бы одно значение или действие.
    if not tokens:
        # Останавливаем вычисление с пояснением, что пустое выражение недопустимо.
        raise ValueError("Выражение пустое. Укажите числа и операции через пробел.")

    # Создаём пустой список, который будет представлять стек операндов.
    stack: list[Number] = []
    # Обрабатываем токены по порядку и нумеруем шаги, начиная с единицы.
    for step, token in enumerate(tokens, start=1):
        # Если токен не является оператором, рассматриваем его как число.
        if token not in OPERATORS:
            # Преобразуем токен в число и помещаем его на вершину стека.
            stack.append(_parse_number(token))
        # Иначе обрабатываем один из поддерживаемых операторов.
        else:
            # Проверяем, имеются ли два значения, необходимые для бинарной операции.
            if len(stack) < 2:
                # Сообщаем, какой операции не хватает операндов и сколько значений есть в стеке.
                raise ValueError(
                    # Указываем требуемое число операндов и текущее состояние стека в сообщении.
                    f"Для операции {token!r} нужны два операнда; "
                    # Дополняем сообщение фактическим количеством значений в стеке.
                    f"в стеке сейчас {len(stack)}."
                )

            # Отдельно выполняем специальную операцию с правилами для нулевых операндов.
            if token == "~":
                # Читаем верхнее значение стека, не удаляя его до выбора правила.
                right = stack[-1]
                # Читаем значение непосредственно под вершиной стека.
                left = stack[-2]
                # Если хотя бы один операнд равен нулю, применяем особое правило.
                if left == 0 or right == 0:
                    # Суммируем все значения стека, включая два операнда операции.
                    total = sum(stack)
                    # Заменяем весь стек квадратом общей суммы.
                    stack[:] = [total**2]
                # Если оба операнда ненулевые, вычисляем модуль их разности.
                else:
                    # Удаляем правый операнд с вершины стека.
                    stack.pop()
                    # Удаляем левый операнд, который теперь находится на вершине.
                    stack.pop()
                    # Помещаем вычисленную абсолютную разность обратно в стек.
                    stack.append(abs(left - right))
            # Для обычных бинарных арифметических операций извлекаем оба операнда.
            else:
                # Снимаем правый операнд с вершины стека.
                right = stack.pop()
                # Снимаем следующий элемент как левый операнд.
                left = stack.pop()
                # Складываем операнды для операции сложения.
                if token == "+":
                    # Сохраняем результат сложения.
                    result = left + right
                # Вычитаем правый операнд из левого.
                elif token == "-":
                    # Сохраняем результат вычитания.
                    result = left - right
                # Перемножаем операнды для операции умножения.
                elif token == "*":
                    # Сохраняем результат умножения.
                    result = left * right
                # Оставшийся обычный оператор — деление.
                elif token == "!":
                    result = left ** right
                else:
                    # Проверяем делитель до выполнения операции.
                    if right == 0:
                        # Не допускаем деление на ноль и возвращаем русскоязычное сообщение.
                        raise ValueError("На ноль делить нельзя :3")
                    # Делим левый операнд на правый.
                    result = left / right
                # Помещаем результат арифметической операции на вершину стека.
                stack.append(result)

        # Записываем состояние стека после каждого успешно обработанного токена, если включена трассировка.
        if trace is not None:
            # Показываем номер шага, обработанный токен и текущее содержимое стека.
            print(f"Шаг {step} ({token}): стек = {stack}", file=trace)

    # Проверяем, что в конце вычисления осталось ровно одно значение-результат.
    if len(stack) != 1:
        # Объясняем, что выражение сформировало неправильное количество результатов.
        raise ValueError(
            # Вставляем в сообщение число оставшихся значений.
            f"Вычисление завершилось с {len(stack)} значениями в стеке; "
            # Просим пользователя проверить корректность постфиксного выражения.
            "проверьте выражение."
        )
    # Возвращаем единственное оставшееся значение как итог вычисления.
    return stack[0]


# Функция разбирает аргументы командной строки, запускает вычисление и печатает результат.
def main(argv: list[str] | None = None) -> int:
    # Создаём парсер, который формирует стандартную справку и ошибки CLI.
    parser = argparse.ArgumentParser(
        # Описываем назначение программы в справке командной строки.
        description="Вычислить арифметическое выражение в постфиксной нотации."
    )
    # Добавляем позиционный аргумент, который может состоять из нескольких токенов.
    parser.add_argument(
        # Называем аргумент, содержащий переданное выражение.
        "expression",
        # Принимаем один или более элементов командной строки.
        nargs="+",
        # Показываем пример формата выражения в CLI-справке.
        help="операнды и операции, разделённые пробелами (например: '2 3 +')",
    )
    # Читаем аргументы из argv или из командной строки, если argv не передан.
    args = parser.parse_args(argv)
    # Соединяем полученные токены пробелами, чтобы восстановить выражение.
    expression = " ".join(args.expression)

    # Запускаем вычисление и выводим трассировку в стандартный поток вывода.
    try:
        # Вычисляем выражение, передавая stdout как место для состояния стека.
        result = evaluate(expression, trace=sys.stdout)
    # Преобразуем ожидаемые ошибки выражения в стандартное сообщение argparse.
    except ValueError as error:
        # Печатаем ошибку вместе со справкой и завершаем CLI с ненулевым кодом.
        parser.error(str(error))

    # Выводим исходное выражение и вычисленный результат в требуемом формате.
    print(f"{expression} = {result}")
    # Возвращаем успешный код завершения программы.
    return 0


# Выполняем CLI-точку входа только при непосредственном запуске этого файла.
if __name__ == "__main__":
    # Завершаем процесс с кодом, возвращённым функцией main.
    raise SystemExit(main())
